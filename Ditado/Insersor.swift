import AppKit
import ApplicationServices

/// Põe o texto no campo em foco de qualquer app, colando pela área de transferência.
enum Insersor {
    enum Resultado { case colado, soCopiado }

    private static let transitorio = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let gerado = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    // Uma colagem ainda não desfeita: o que o usuário tinha antes e a marca da nossa escrita.
    private static var reserva: [NSPasteboardItem]?
    private static var contagemNossa = -1
    private static var restauracao: DispatchWorkItem?

    static var temAcessibilidade: Bool { AXIsProcessTrusted() }

    static func pedirAcessibilidade() {
        let opcoes = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
        _ = AXIsProcessTrustedWithOptions(opcoes)
    }

    /// Cola o texto e devolve a área de transferência ao que era. Sem permissão de
    /// Acessibilidade não dá para apertar ⌘V pelo usuário: o texto fica copiado.
    @discardableResult
    static func inserir(_ texto: String) -> Resultado {
        let area = NSPasteboard.general
        guard temAcessibilidade else {
            area.clearContents()
            area.setString(texto, forType: .string)
            return .soCopiado
        }
        // Duas colagens seguidas: a área ainda tem o nosso texto anterior, não o do usuário.
        // Vale a reserva feita na primeira, e a restauração dela é adiada.
        restauracao?.cancel()
        let guardado: [NSPasteboardItem]
        if let reserva, area.changeCount == contagemNossa { guardado = reserva } else { guardado = copia(de: area) }
        reserva = guardado
        area.clearContents()
        // Os marcadores pedem aos gerenciadores de área de transferência que não guardem este item.
        area.declareTypes([.string, transitorio, gerado], owner: nil)
        area.setString(texto, forType: .string)
        area.setData(Data(), forType: transitorio)
        area.setData(Data(), forType: gerado)
        let contagem = area.changeCount
        contagemNossa = contagem
        apertar(9, com: .maskCommand) // ⌘V
        // Texto longo demora mais para o app de destino ler.
        let espera = min(3.0, 0.7 + Double(texto.count) / 20_000)
        let item = DispatchWorkItem {
            reserva = nil
            contagemNossa = -1
            guard area.changeCount == contagem else { return } // o usuário copiou outra coisa nesse meio tempo
            area.clearContents()
            if !guardado.isEmpty { area.writeObjects(guardado) }
        }
        restauracao = item
        DispatchQueue.main.asyncAfter(deadline: .now() + espera, execute: item)
        return .colado
    }

    private static func apertar(_ tecla: CGKeyCode, com modificadores: CGEventFlags) {
        let fonte = CGEventSource(stateID: .combinedSessionState)
        for baixo in [true, false] {
            let evento = CGEvent(keyboardEventSource: fonte, virtualKey: tecla, keyDown: baixo)
            evento?.flags = modificadores
            evento?.post(tap: .cghidEventTap)
        }
    }

    private static func copia(de area: NSPasteboard) -> [NSPasteboardItem] {
        (area.pasteboardItems ?? []).map { item in
            let novo = NSPasteboardItem()
            for tipo in item.types {
                if let dados = item.data(forType: tipo) { novo.setData(dados, forType: tipo) }
            }
            return novo
        }
    }
}
